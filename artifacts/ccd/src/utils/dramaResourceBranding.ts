export function isDramaResourceLibraryCategory(
  categoryName: string | undefined | null,
): boolean {
  const n = String(categoryName || '').trim();
  if (!n) return false;
  if (n.startsWith('Drama Resource') || n.startsWith('DR ')) return true;
  return false;
}
