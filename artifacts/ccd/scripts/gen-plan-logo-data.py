#!/usr/bin/env python3
"""Regenerate src/utils/planLogoData.ts from public/ccdesigner-logo-colour.png.

public/ccdesigner-logo-colour.png is the canonical colour export logo: the
master brand file (CCDesigner_logo_transparent.png, 3319x903) trimmed to
784x192, transparent, supplied with the in-lesson proposal v3.

The plan logo is embedded (base64 PNG, colour, 120px tall = 3x print size) so
print windows, the PDF service and Word export never depend on fetching
/ccdesigner-logo.png. Run from artifacts/ccd: python3 scripts/gen-plan-logo-data.py
"""
import base64, io
from PIL import Image

SRC = 'public/ccdesigner-logo-colour.png'
OUT = 'src/utils/planLogoData.ts'
H = 120

im = Image.open(SRC).convert('RGBA')
w = round(im.width * H / im.height)
small = im.resize((w, H), Image.LANCZOS)
buf = io.BytesIO()
small.save(buf, 'PNG', optimize=True)
b64 = base64.b64encode(buf.getvalue()).decode('ascii')
lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
body = ' +\n  '.join(f"'{l}'" for l in lines)
with open(OUT, 'w') as f:
    f.write(
        '/* eslint-disable */\n'
        '// GENERATED by scripts/gen-plan-logo-data.py from public/ccdesigner-logo-colour.png. Do not edit by hand.\n'
        '// CCDesigner colour logo (ribbon mark + "designer"), PNG with transparency.\n'
        f'export const PLAN_LOGO_PNG_WIDTH = {w};\n'
        f'export const PLAN_LOGO_PNG_HEIGHT = {H};\n'
        'export const PLAN_LOGO_PNG_BASE64 =\n  ' + body + ';\n'
    )
print(OUT, w, H, len(buf.getvalue()), 'bytes')
