#!/usr/bin/env node
/**
 * Generates supabase/migrations/20261013120100_partner_directory_seed.sql from the
 * same uk-hub-map.json the UI renders, so map, list, search and database rows
 * share one set of ONS codes and ACE hub ids.
 *
 *   node artifacts/ccd/scripts/build-hub-directory-seed.mjs
 *
 * Every INSERT is ON CONFLICT DO NOTHING: re-running never overwrites rows that
 * admins have since edited.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const map = JSON.parse(readFileSync(resolve(here, '../public/music-hubs/uk/uk-hub-map.json'), 'utf8'));
const out = resolve(here, '../../../supabase/migrations/20261013120100_partner_directory_seed.sql');

const ACE_SOURCE = 'https://www.artscouncil.org.uk/our-open-funds/music-hub-investment';
const GE_SOURCE = 'https://www.greateressexmusichub.org.uk/site/';

const slugify = (s) =>
  s.toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (Array.isArray(v)) return `ARRAY[${v.map(q).join(', ')}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

/** Constituent services we have verified on the hub's own site. */
const SERVICES = [
  {
    id: 'essex-music-service',
    hub: 'greater-essex',
    name: 'Essex Music Service',
    role: 'lead',
    organisation: 'ems',
    site: 'https://www.essexmusicservice.org.uk/site/',
    match: (lad) => lad.county === 'Essex',
  },
  {
    id: 'music-on-sea',
    hub: 'greater-essex',
    name: 'Music-on-Sea (Southend)',
    role: 'partner',
    organisation: null,
    site: null,
    match: (lad) => lad.name === 'Southend-on-Sea',
  },
  {
    id: 'thurrock-music-service',
    hub: 'greater-essex',
    name: 'Thurrock Music Service',
    role: 'partner',
    organisation: null,
    site: null,
    match: (lad) => lad.name === 'Thurrock',
  },
];

const lines = [];
const push = (s) => lines.push(s);

push(`-- =============================================================================
-- Partner Hubs directory seed — GENERATED by artifacts/ccd/scripts/build-hub-directory-seed.mjs
-- Source: uk-hub-map.json v${map.version} (ONS LAD/RGN/CTRY Dec 2024, OGL v3; ACE Music Hub lead organisations)
-- Additive only: every INSERT is ON CONFLICT DO NOTHING (admin edits are never overwritten).
-- =============================================================================
`);

push(`-- Essex Music Service organisation (lead partner of Greater Essex Music Hub)
INSERT INTO public.organisations (
  id, name, partner_slug, slug, display_name, short_name, site_url, logo_src,
  primary_color, accent_color, logo_on_plate, paid, interactive, status, aliases
) VALUES (
  'ems', 'Essex Music Service', 'ems', 'ems', 'Essex Music Service', 'EMS',
  'https://www.essexmusicservice.org.uk/site/', '/partners/essex-music-service.svg',
  '#330968', '#7a00df', false, false, true, 'active', ARRAY['essex-music-service', 'greater-essex']
)
ON CONFLICT DO NOTHING;
`);

push('-- Music Hubs (Arts Council England hub areas)');
for (const h of map.hubs) {
  const isGE = h.id === 'greater-essex';
  push(`INSERT INTO public.music_hubs (
  id, name, short_name, ace_area_name, nation_code, region_code, region_codes, region_note,
  lead_organisation_name, lead_body, organisation_id, site_url, verified, source_url, relationship_status, status
) VALUES (
  ${q(h.id)}, ${q(h.name)}, ${q(h.shortName)}, ${q(h.aceAreaName)}, 'E92000001', ${q(h.region)}, ${q(h.regions || [h.region])}, ${q(h.regionNote)},
  ${q(h.leadOrganisation)}, ${q(h.leadBody)}, ${isGE ? "(SELECT id FROM public.organisations WHERE id = 'ems')" : 'NULL'}, ${q(h.siteUrl)}, ${q(Boolean(h.verified))}, ${q(isGE ? GE_SOURCE : ACE_SOURCE)}, ${q(isGE ? 'demonstration' : 'directory_listing')}, 'published'
) ON CONFLICT (id) DO NOTHING;`);
}
push('');

push('-- Hub services: verified constituent services, plus each hub\'s ACE-listed lead');
const serviceIds = new Set(SERVICES.map((s) => s.hub));
SERVICES.forEach((s, i) => {
  push(`INSERT INTO public.music_hub_services (id, hub_id, name, role, organisation_id, site_url, verified, sort_order)
VALUES (${q(s.id)}, ${q(s.hub)}, ${q(s.name)}, ${q(s.role)}, ${s.organisation ? `(SELECT id FROM public.organisations WHERE id = ${q(s.organisation)})` : 'NULL'}, ${q(s.site)}, true, ${i})
ON CONFLICT (id) DO NOTHING;`);
});
for (const h of map.hubs) {
  if (serviceIds.has(h.id) || !h.leadOrganisation) continue;
  push(`INSERT INTO public.music_hub_services (id, hub_id, name, role, site_url, verified, sort_order)
VALUES (${q(`${h.id}-lead`)}, ${q(h.id)}, ${q(h.leadOrganisation)}, 'lead', NULL, ${q(Boolean(h.verified))}, 0)
ON CONFLICT (id) DO NOTHING;`);
}
push('');

push('-- Local authority districts (ONS LAD December 2024), all UK nations');
const rows = map.lads.map((l) => {
  const svc = SERVICES.find((s) => s.hub === l.hub && s.match(l));
  return `(${q(l.code)}, ${q(slugify(l.name))}, ${q(l.name)}, ${q(l.nation)}, ${q(l.region)}, ${q(l.county)}, ${q(l.hub)}, ${q(svc?.id ?? null)})`;
});
for (let i = 0; i < rows.length; i += 60) {
  push(`INSERT INTO public.music_hub_areas (code, slug, name, nation_code, region_code, county, hub_id, service_id) VALUES
${rows.slice(i, i + 60).join(',\n')}
ON CONFLICT (code) DO NOTHING;`);
}
push('');

push(`-- Essex Music Service prototype packs already in the app (files in /demo-resources)
INSERT INTO public.resources (
  id, title, description, resource_type, partner_slug, filename, download_url, requires_auth, is_active,
  organisation_id, status, is_free, key_stages, subjects, tags, metadata, published_at,
  access_level, contributor_name, licence, source_url
)
SELECT v.id, v.title, v.description, v.rtype, 'ems', v.filename, v.url, false, true,
  'ems', 'published', true, v.ks, v.subjects, v.tags, v.meta::jsonb, NOW(),
  'free', 'Essex Music Service', 'Shared by Essex Music Service for planning; © Essex Music Service', v.source
FROM (VALUES
  ('ems-schools-brochure', 'Schools brochure',
   'Essex Music Service’s offer to schools: curriculum platforms, instrumental and vocal pathways, workshops and CPD.',
   'pdf', 'ems-schools-brochure.pdf', '/demo-resources/ems-schools-brochure.pdf',
   ARRAY['KS3']::text[], ARRAY['Music']::text[], ARRAY['brochure']::text[],
   '{"type":"PDF","phase_label":"KS3 (set up for Years 7–8)","library_pack":"ems-schools-brochure"}',
   'https://www.essexmusicservice.org.uk/site/'),
  ('ems-dj-workshop', 'DJ Workshop',
   'Featured EMS workshop: beat-matching, structure and performance. Course notes plus a ready-made lesson sequence.',
   'pdf', 'ems-dj-workshop-course-notes.pdf', '/demo-resources/ems-dj-workshop-course-notes.pdf',
   ARRAY['KS2','KS3']::text[], ARRAY['Music technology']::text[], ARRAY['workshop']::text[],
   '{"type":"Workshop","phase_label":"KS2–KS3","library_pack":"ems-dj-workshop"}',
   'https://www.essexmusicservice.org.uk/site/workshops/'),
  ('ems-rap-it-workshop', 'Rap-It!',
   'Literacy-linked rap writing and performance workshop from Essex Music Service, with course notes and lessons.',
   'pdf', 'ems-rap-it-workshop-course-notes.pdf', '/demo-resources/ems-rap-it-workshop-course-notes.pdf',
   ARRAY['KS2','KS3','KS4']::text[], ARRAY['Music','English']::text[], ARRAY['workshop']::text[],
   '{"type":"Workshop","phase_label":"KS2–KS4","library_pack":"ems-rap-it-workshop"}',
   'https://www.essexmusicservice.org.uk/site/workshops/')
) AS v(id, title, description, rtype, filename, url, ks, subjects, tags, meta, source)
WHERE EXISTS (SELECT 1 FROM public.organisations WHERE id = 'ems')
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.resource_scopes (resource_id, scope_type, scope_id)
SELECT r.id, 'hub', 'greater-essex'
FROM public.resources r
WHERE r.id IN ('ems-schools-brochure', 'ems-dj-workshop', 'ems-rap-it-workshop')
ON CONFLICT DO NOTHING;
`);

writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`Wrote ${out} — ${map.hubs.length} hubs, ${map.lads.length} areas`);
