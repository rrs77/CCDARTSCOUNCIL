#!/usr/bin/env node
/**
 * Generates supabase/migrations/20261013120100_partner_directory_seed.sql from
 * the same files the app reads:
 *   public/music-hubs/uk/uk-hub-map.json            ONS areas + ACE hubs (geometry, codes)
 *   src/components/hubsPreview/directorySeed.json   verified services, about, contact, resources
 *
 *   node artifacts/ccd/scripts/build-hub-directory-seed.mjs
 *
 * Every INSERT is ON CONFLICT DO NOTHING: re-running never overwrites rows that
 * admins have since edited.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (p) => JSON.parse(readFileSync(resolve(here, p), 'utf8'));
const map = read('../public/music-hubs/uk/uk-hub-map.json');
const seed = read('../src/components/hubsPreview/directorySeed.json');
const out = resolve(here, '../../../supabase/migrations/20261013120100_partner_directory_seed.sql');

const ACE_SOURCE = 'https://www.artscouncil.org.uk/our-open-funds/music-hub-investment';

const slugify = (s) =>
  s.toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (Array.isArray(v)) return `ARRAY[${v.map(q).join(', ')}]::text[]`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const orgRef = (id) => (id ? `(SELECT id FROM public.organisations WHERE id = ${q(id)})` : 'NULL');
const covers = (svc, lad) =>
  lad.hub === svc.hubId &&
  (svc.covers.county ? lad.county === svc.covers.county : lad.name === svc.covers.name);

const lines = [];
const push = (s) => lines.push(s);

push(`-- =============================================================================
-- Partner Hubs directory seed — GENERATED by artifacts/ccd/scripts/build-hub-directory-seed.mjs
-- Sources: uk-hub-map.json v${map.version} (ONS LAD/RGN/CTRY Dec 2024, OGL v3; ACE Music Hub lead
-- organisations) and src/components/hubsPreview/directorySeed.json (verified local detail).
-- Additive only: every INSERT is ON CONFLICT DO NOTHING (admin edits are never overwritten).
-- =============================================================================
`);

push('-- Organisations referenced by the directory (existing rows are left untouched)');
for (const o of seed.organisations) {
  push(`INSERT INTO public.organisations (
  id, name, partner_slug, slug, display_name, short_name, site_url, logo_src,
  primary_color, accent_color, logo_on_plate, paid, interactive, status, aliases
) VALUES (
  ${q(o.id)}, ${q(o.name)}, ${q(o.id)}, ${q(o.id)}, ${q(o.name)}, ${q(o.shortName)}, ${q(o.siteUrl)}, ${q(o.logoSrc)},
  ${q(o.primaryColor)}, ${q(o.accentColor)}, false, false, true, 'active', ${q(o.aliases)}
) ON CONFLICT DO NOTHING;`);
}
push('');

push('-- Music Hubs (Arts Council England hub areas)');
for (const h of map.hubs) {
  const extra = seed.hubs[h.id] ?? {};
  push(`INSERT INTO public.music_hubs (
  id, name, short_name, ace_area_name, nation_code, region_code, region_codes, region_note,
  lead_organisation_name, lead_body, organisation_id, site_url, about, contact, verified, source_url,
  relationship_status, status
) VALUES (
  ${q(h.id)}, ${q(h.name)}, ${q(h.shortName)}, ${q(h.aceAreaName)}, 'E92000001', ${q(h.region)}, ${q(h.regions || [h.region])}, ${q(h.regionNote)},
  ${q(h.leadOrganisation)}, ${q(h.leadBody)}, ${orgRef(extra.organisationId)}, ${q(h.siteUrl)}, ${q(extra.about)}, ${q(extra.contact ?? {})}, ${q(Boolean(h.verified))}, ${q(extra.sourceUrl ?? ACE_SOURCE)},
  ${q(extra.relationship ?? 'directory_listing')}, 'published'
) ON CONFLICT (id) DO NOTHING;`);
}
push('');

push("-- Hub services: verified constituent services, plus each other hub's ACE-listed lead");
const detailed = new Set(seed.services.map((s) => s.hubId));
seed.services.forEach((s, i) => {
  push(`INSERT INTO public.music_hub_services (id, hub_id, name, role, organisation_id, site_url, verified, sort_order)
VALUES (${q(s.id)}, ${q(s.hubId)}, ${q(s.name)}, ${q(s.role)}, ${orgRef(s.organisationId)}, ${q(s.siteUrl)}, true, ${i})
ON CONFLICT (id) DO NOTHING;`);
});
for (const h of map.hubs) {
  if (detailed.has(h.id) || !h.leadOrganisation) continue;
  push(`INSERT INTO public.music_hub_services (id, hub_id, name, role, site_url, verified, sort_order)
VALUES (${q(`${h.id}-lead`)}, ${q(h.id)}, ${q(h.leadOrganisation)}, 'lead', NULL, ${q(Boolean(h.verified))}, 0)
ON CONFLICT (id) DO NOTHING;`);
}
push('');

push('-- Local authority districts (ONS LAD December 2024), all UK nations');
const rows = map.lads.map((l) => {
  const svc = seed.services.find((s) => covers(s, l));
  return `(${q(l.code)}, ${q(slugify(l.name))}, ${q(l.name)}, ${q(l.nation)}, ${q(l.region)}, ${q(l.county)}, ${q(l.hub)}, ${q(svc?.id ?? null)})`;
});
for (let i = 0; i < rows.length; i += 60) {
  push(`INSERT INTO public.music_hub_areas (code, slug, name, nation_code, region_code, county, hub_id, service_id) VALUES
${rows.slice(i, i + 60).join(',\n')}
ON CONFLICT (code) DO NOTHING;`);
}
push('');

push('-- Published partner resources (files already shipped in /demo-resources) and their scopes');
for (const r of seed.resources) {
  const meta = { type: r.type, phase_label: r.phaseLabel, library_pack: r.libraryPack };
  push(`INSERT INTO public.resources (
  id, title, description, resource_type, partner_slug, filename, download_url, requires_auth, is_active,
  organisation_id, status, is_free, key_stages, subjects, metadata, published_at,
  access_level, contributor_name, licence, source_url
)
SELECT ${q(r.id)}, ${q(r.title)}, ${q(r.description)}, ${q(r.type === 'PDF' ? 'pdf' : 'workshop')}, ${q(r.organisationId)}, ${q(r.previewHref.split('/').pop())}, ${q(r.previewHref)}, false, true,
  ${q(r.organisationId)}, 'published', ${q(r.access === 'free')}, ${q(r.keyStages)}, ${q(r.subjects)}, ${q(meta)}, NOW(),
  ${q(r.access)}, ${q(r.contributor)}, ${q(r.licence)}, ${q(r.sourceHref)}
WHERE EXISTS (SELECT 1 FROM public.organisations WHERE id = ${q(r.organisationId)})
ON CONFLICT (id) DO NOTHING;`);
  for (const s of r.scopes) {
    push(`INSERT INTO public.resource_scopes (resource_id, scope_type, scope_id)
SELECT ${q(r.id)}, ${q(s.type)}, ${q(s.id)} WHERE EXISTS (SELECT 1 FROM public.resources WHERE id = ${q(r.id)})
ON CONFLICT DO NOTHING;`);
  }
}

writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`Wrote ${out} — ${map.hubs.length} hubs, ${map.lads.length} areas, ${seed.resources.length} resources`);
